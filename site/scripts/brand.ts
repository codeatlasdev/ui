// Prebuild: renders the favicon / app-icon set from src/brand/mark.svg and the theme, into
// public/brand/ (Astro copies it to dist) and writes src/generated/brand.ts with the hashed URLs.
// Per-page social cards are rendered later, from the built pages (scripts/og-integration.ts).
// Nothing this writes is committed (see .gitignore).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { generateBrand } from "@codeatlasdev/ui/vite";
import { theme } from "../src/theme.ts";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const assets = await generateBrand({
	mark: readFileSync(resolve(root, "src/brand/mark.svg"), "utf8"),
	theme,
	outDir: resolve(root, "public/brand"),
	name: "CodeAtlas UI",
	shortName: "CodeAtlas UI",
});
const out = resolve(root, "src/generated/brand.ts");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
	out,
	`// Generated by scripts/brand.ts. Do not edit or commit.\nexport const brand = ${JSON.stringify(assets, null, "\t")} as const;\n`
);
console.log(`brand: icons ${assets.hash}`);
