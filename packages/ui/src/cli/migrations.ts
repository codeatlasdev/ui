/**
 * The migration registry (#382): one `migrations/<major>.json` per major, written when the breaking
 * change ships. The same data produces MIGRATION.md, `dist/migrations.json`, the MCP `get_migration`
 * tool and the `migrate --from --to` report, and it is what the release policy checks a major
 * changeset against.
 */
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export type MigrationKind = "rename" | "removed" | "behavior";
/** `yes`: `migrate` rewrites it. `partial`: it rewrites what it can and reports the rest. `no`: a person does it. */
export type CodemodSupport = "yes" | "partial" | "no";

export interface MigrationEntry {
	/** `v<major>-<slug>`, the handle used in dev warnings, changesets and reports. */
	id: string;
	kind: MigrationKind;
	/** Changeset hashes (as printed in CHANGELOG.md) this entry documents. */
	changesets: string[];
	/** What to look for in your code (before). */
	selector: string;
	/** What to write instead (after). */
	replacement: string;
	/**
	 * Regex (per line, in `.svelte` `.ts` `.js` `.astro` `.css` `.mdx`) that finds the old API, so `migrate`
	 * reports file:line for what it cannot rewrite. Absent when the old usage is not greppable.
	 */
	detect?: string;
	codemod: CodemodSupport;
	/** The `migrate` rule that implements it; required unless `codemod` is `no`. */
	codemodId?: string;
	/** Why, and what is left for a human. */
	note: string;
}

export interface MigrationFile {
	major: number;
	/** The release that shipped it, e.g. `3.0.0`. */
	version: string;
	title: string;
	entries: MigrationEntry[];
}

/**
 * In the repo the registry is `migrations/*.json` at the package root. The published package ships
 * only `dist/`, where the build writes the same data as `dist/migrations.json` (next to `dist/bin`).
 */
export function loadMigrations(): MigrationFile[] {
	const here = dirname(fileURLToPath(import.meta.url));
	for (const rel of ["../../migrations", "../migrations"]) {
		const dir = join(here, rel);
		if (existsSync(dir))
			return readdirSync(dir)
				.filter((f) => /^\d+\.json$/.test(f))
				.map((f) => JSON.parse(readFileSync(join(dir, f), "utf8")) as MigrationFile)
				.sort((a, b) => a.major - b.major);
	}
	for (const rel of ["../migrations.json", "../../migrations.json"]) {
		const file = join(here, rel);
		if (existsSync(file)) return JSON.parse(readFileSync(file, "utf8")).migrations;
	}
	throw new Error("migrations not found (migrations/*.json or dist/migrations.json)");
}

/** The majors a project crosses going from major `from` to major `to`: (from, to]. */
export function migrationsBetween(
	from: number,
	to: number,
	files: MigrationFile[] = loadMigrations()
): MigrationFile[] {
	return files.filter((m) => m.major > from && m.major <= to);
}

const KIND_LABEL: Record<MigrationKind, string> = {
	rename: "renamed",
	removed: "removed",
	behavior: "behavior",
};

/** MIGRATION.md: per major, each change as before -> after with why and whether `migrate` covers it. */
export function migrationMarkdown(files: MigrationFile[]): string {
	const out = [
		"<!-- generated by packages/ui/scripts/build-manifest.ts from migrations/*.json. Do not edit. -->",
		"# Migration guide",
		"",
		"Every breaking change per major release, newest first: what to look for (before), what to write (after), why, and whether `bunx @codeatlasdev/ui migrate --from <major> --to <major> --write` covers it. `yes` is rewritten, `partial` is rewritten where it is static and reported (file:line) where it is not, `no` is yours to do. The same data is in `dist/migrations.json` and the MCP tool `get_migration`.",
		"",
	];
	for (const m of [...files].reverse()) {
		out.push(`## ${m.version}`, "", `${m.title}.`, "");
		for (const e of m.entries)
			out.push(
				`### \`${e.id}\``,
				"",
				`- **Before** (${KIND_LABEL[e.kind]}): ${e.selector}`,
				`- **After**: ${e.replacement}`,
				`- **migrate**: ${e.codemod}${e.codemodId ? ` (\`${e.codemodId}\`)` : ""}`,
				`- **Why / notes**: ${e.note}`,
				""
			);
	}
	return `${out.join("\n").trimEnd()}\n`;
}

/** A whole line `Migration: v3-grid-columns[, v3-row-to-flex]`: prose that merely starts with "Migration:" is not a citation. */
const MARKER = /^\s*Migration:\s*(v\d+-[a-z0-9-]+(?:\s*,\s*v\d+-[a-z0-9-]+)*)\s*$/gm;

/** Migration ids a text cites with `Migration: id[, id]` lines. */
function cited(text: string): string[] {
	return [...text.matchAll(MARKER)].flatMap((m) => m[1].split(/\s*,\s*/));
}

/** A `major` changeset must cite existing migration ids; returns the problem, or undefined. */
export function checkChangeset(source: string, ids: Set<string>): string | undefined {
	const front = source.match(/^---\n([\s\S]*?)\n---/)?.[1] ?? "";
	if (!/@codeatlasdev\/ui"?:\s*major/.test(front)) return undefined;
	const used = cited(source);
	if (!used.length)
		return "a major changeset needs a `Migration: <id>` line naming an entry of migrations/<major>.json";
	const unknown = used.filter((id) => !ids.has(id));
	return unknown.length ? `unknown migration id: ${unknown.join(", ")}` : undefined;
}

/**
 * Every bullet under a `### Major Changes` heading of CHANGELOG.md is covered, either by a registry
 * entry listing its changeset hash or by a `Migration: id` line. Returns one message per gap.
 */
export function checkChangelog(changelog: string, files: MigrationFile[]): string[] {
	const ids = new Set(files.flatMap((m) => m.entries.map((e) => e.id)));
	const known = new Set(files.flatMap((m) => m.entries.flatMap((e) => e.changesets)));
	const problems: string[] = [];
	let version = "";
	let major = false;
	let bullet: { hash: string; text: string } | undefined;
	const flush = () => {
		if (!bullet) return;
		const used = cited(bullet.text);
		const unknown = used.filter((id) => !ids.has(id));
		if (unknown.length) problems.push(`${version}: unknown migration id ${unknown.join(", ")}`);
		else if (!used.length && !known.has(bullet.hash))
			problems.push(`${version}: major change without a Migration id (${bullet.hash})`);
		bullet = undefined;
	};
	for (const line of changelog.split("\n")) {
		const v = line.match(/^## (\S+)/);
		if (v) {
			flush();
			version = v[1];
			major = false;
			continue;
		}
		const h = line.match(/^### (.+)/);
		if (h) {
			flush();
			major = h[1] === "Major Changes";
			continue;
		}
		if (!major) continue;
		const b = line.match(/^- ([0-9a-f]{7}): /);
		if (b) {
			flush();
			bullet = { hash: b[1], text: line };
		} else if (bullet) bullet.text += `\n${line}`;
	}
	flush();
	return problems;
}
