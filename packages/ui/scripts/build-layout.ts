// Renders src/lib/styles/layout.css: the attribute rules behind the layout token props
// (`data-gap="4"`, `data-md-p="2"`, ...). Run: bun scripts/build-layout.ts   (--check fails if stale)
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import {
	ALIGN,
	BREAKPOINTS,
	COLUMNS,
	DIRECTION,
	JUSTIFY,
	SPACE,
} from "../src/lib/components/Layout/layout.ts";

const flex = (v: string) => (v === "start" || v === "end" ? `flex-${v}` : v);
const justify = (v: string) =>
	v === "between" || v === "around" || v === "evenly" ? `space-${v}` : flex(v);

/** Steps that also get breakpoint variants: half steps and 7/11 are fine-tuning, rarely responsive. */
const RESPONSIVE_SPACE: readonly number[] = SPACE.filter(
	(n) => Number.isInteger(n) && n !== 7 && n !== 11
);

/** [prop, value, declaration] for every rule; `responsive` limits it to what breakpoints also style. */
function rules(responsive: boolean): [string, string, string][] {
	const out: [string, string, string][] = [];
	const token = (n: number) => `var(--ca-space-${String(n).replace(".", "-")})`;
	for (const n of responsive ? RESPONSIVE_SPACE : SPACE) {
		out.push(["gap", String(n), `gap:${token(n)}`]);
		out.push(["p", String(n), `padding:${token(n)}`]);
		out.push(["px", String(n), `padding-inline:${token(n)}`]);
		out.push(["py", String(n), `padding-block:${token(n)}`]);
	}
	for (const a of ALIGN) out.push(["align", a, `align-items:${flex(a)}`]);
	for (const j of JUSTIFY) out.push(["justify", j, `justify-content:${justify(j)}`]);
	for (const d of DIRECTION) out.push(["direction", d, `flex-direction:${d}`]);
	for (const c of COLUMNS)
		out.push(["columns", String(c), `grid-template-columns:repeat(${c},minmax(0,1fr))`]);
	out.push(["wrap", "true", "flex-wrap:wrap"]);
	return out;
}

export function layoutCSS(): string {
	const block = (prefix: string, indent: string, responsive: boolean) =>
		rules(responsive)
			.map(([p, v, d]) => `${indent}[data-${prefix}${p}="${v}"]{${d}}`)
			.join("\n");
	const parts = [
		"/* generated by scripts/build-layout.ts — do not edit */",
		"/* Layout token props: a prop becomes data-<prop>, a responsive entry data-<bp>-<prop>. Breakpoints are the shared scale. */",
		block("", "", false),
	];
	for (const [bp, px] of Object.entries(BREAKPOINTS))
		parts.push(`@media (min-width:${px}px){\n${block(`${bp}-`, "  ", true)}\n}`);
	return `${parts.join("\n")}\n`;
}

if (import.meta.main) {
	const file = join(import.meta.dir, "../src/lib/styles/layout.css");
	const css = layoutCSS();
	if (process.argv.includes("--check")) {
		if (readFileSync(file, "utf8") !== css) {
			console.error(`stale: ${file}\nrun: bun scripts/build-layout.ts`);
			process.exit(1);
		}
	} else writeFileSync(file, css);
}
