/**
 * Builds the React UI equivalence table (#383) from `equivalents/react-ui.json`:
 *   dist/equivalents.json   the rows, with the import path of every target taken from the manifest
 *   migrate-react.mdx       the table between the `equivalents` markers, so the guide cannot drift
 * `--check` fails instead of writing when the guide is stale (the unit test runs the same comparison).
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { equivalentsMarkdown, loadEquivalents } from "../src/cli/equivalents.ts";
import { buildManifest } from "./build-manifest.ts";

const ROOT = resolve(import.meta.dir, "..");
export const GUIDE = resolve(ROOT, "../../site/src/content/docs/getting-started/migrate-react.mdx");
export const START = "{/* equivalents:start (generated by build-equivalents.ts, do not edit) */}";
export const END = "{/* equivalents:end */}";

/** `guide` with the block between the markers replaced by the table of `rows`. */
export function withTable(guide: string, table: string): string {
	const a = guide.indexOf(START);
	const b = guide.indexOf(END);
	if (a === -1 || b === -1 || b < a) throw new Error(`${GUIDE}: equivalents markers are missing`);
	return `${guide.slice(0, a + START.length)}\n\n${table.trim()}\n\n${guide.slice(b)}`;
}

if (import.meta.main) {
	const rows = loadEquivalents();
	const manifest = buildManifest();
	const entryOf = Object.fromEntries(
		[...manifest.components, ...manifest.exports].map((e) => [e.name, e.import])
	);
	const dist = join(ROOT, "dist");
	mkdirSync(dist, { recursive: true });
	writeFileSync(
		join(dist, "equivalents.json"),
		`${JSON.stringify(
			{
				name: manifest.name,
				version: manifest.version,
				rows: rows.map((r) => ({
					...r,
					imports: Object.fromEntries(r.to.map((n) => [n, entryOf[n]])),
				})),
			},
			null,
			"\t"
		)}\n`
	);
	// Docs live in the monorepo's site/; a build from a published tarball has no guide to update.
	if (existsSync(GUIDE)) {
		const guide = readFileSync(GUIDE, "utf8");
		const next = withTable(guide, equivalentsMarkdown(rows));
		if (process.argv.includes("--check")) {
			if (next !== guide) {
				console.error("migrate-react.mdx is stale: run `bun run --cwd packages/ui equivalents`");
				process.exit(1);
			}
		} else if (next !== guide) writeFileSync(GUIDE, next);
	}
	console.log(`equivalents: ${rows.length} rows`);
}
