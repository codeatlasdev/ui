// Renders src/lib/styles/presets/*.css from src/lib/theme/builtins.ts.
// Run: bun scripts/build-themes.ts   (--check fails if any file is stale)
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { BUILTIN_PRESETS } from "../src/lib/theme/builtins.ts";
import { presetCSS } from "../src/lib/theme/define.ts";

const dir = join(import.meta.dir, "../src/lib/styles/presets");
const check = process.argv.includes("--check");
let stale = 0;

for (const p of BUILTIN_PRESETS) {
	const css = `/* generated by scripts/build-themes.ts — do not edit */\n/* ${p.label} preset (H=${p.hue}) */\n${presetCSS(p, p.id === "amber" ? "root" : "builtin")}\n`;
	const file = join(dir, `${p.id}.css`);
	if (check) {
		if (readFileSync(file, "utf8") !== css) {
			console.error(`stale: ${file}`);
			stale++;
		}
	} else writeFileSync(file, css);
}
if (stale) {
	console.error("run: bun scripts/build-themes.ts");
	process.exit(1);
}
